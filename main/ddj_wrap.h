// main/ddj_wrap.h —— 按字数把一段中文折成多行。
//
// 为什么要自己折：LVGL 的自动换行按空格找断点，而这里整段中文没有空格；
// 实测下来不如算准 —— 同一个字号下汉字等宽，所以「每行几个字」是可以算的，
// 210px 的行宽，24px 字每行 8 个、32px 字每行 6 个。
//
// 纯逻辑，不依赖 LVGL，能在电脑上测（tests/test_ddj_wrap.c）。
#pragma once

#include <stddef.h>

// 折行后的最长形态出现在点拨：48 字按 8 字一行折成 6 行，即 5 个换行。
//   48 字 × 3 字节 + 5 个换行 + NUL = 150 字节，176 留出余量。
// 注意别按原文算：原文 24 字、每行 6 个，只有 4 行 76 字节 —— 那是**最短**
// 的调用者。这个缓冲区被三层共用，必须按最长的那个开。
#define DDJ_WRAP_CAPACITY 176

/* 把 text 折成每行最多 chars_per_line 个字符，行间插入 '\n'。
 *
 * 只按字符数折，不按像素；ASCII 比汉字窄，所以含 ASCII 的行会短一些，这是
 * 有意接受的结果（宁可留白，也不赌一个算不准的宽度）。
 *
 * 一条禁则：收尾标点（，。！？、；：）」』》】…—）不落在行首。
 * 做法是「提前一字换行」，而不是把标点提上一行：
 *   ……天地玄黄宇宙洪 / 荒。      ← 提前换行，两行都不超宽
 *   ……天地玄黄宇宙洪荒。          ← 「提上一行」的写法，这一行多出一个字
 * 后者会超出行宽，被 LVGL 再折一次，行数就不可控了 —— 版式一旦不可控，
 * 「一屏放得下」这个前提就没了。所以这里宁可让某一行少一个字。
 *
 * 两个不处理的情形（都只在退化输入下出现，本项目的正文不会遇到）：
 *   - chars_per_line 为 1，或提前换行会让当前行变空；
 *   - 连续两个收尾标点正好卡在换行点（如「！」后面还有「」」）。
 * 这两种情况下标点仍会落在行首，代码里不假装能解决。
 *
 * 返回写进 out 的字节数（不含 NUL）；容量不足、参数非法时返回 0，并把 out
 * 清成空串。 */
size_t ddj_wrap_utf8(const char *text, int chars_per_line, char *out, size_t capacity);
