// main/qpq_wrap.h —— 中文按字数折行。
//
// 为什么必须自己折：LVGL 的自动换行在空格处断行，而中文没有空格 —— 交给它就会
// 得到一行溢出的长文本。所以所有可能超一行的中文都要先经过这里。
//
// 断点选择规则：一行最多放 chars_per_line 个字（**这是硬保证**），并且在不超过
// 这个宽度的前提下，断点尽量靠后，但要求「下一行的第一个字不是收尾标点」。
// 也就是在候选断点 chars_per_line、chars_per_line-1、… 里向前找第一个满足条件
// 的位置。
//
// 为什么不是更常见的「提前一字」写法（发现行尾后是标点就把断点前移一格）：
// 那个写法在**连续标点**处会失效。例如 「甲，。」 里逗号正好落在行尾、句号落在
// 下一行行首时，「提前一字」的触发条件（当前字不是标点）不成立，于是句号照样
// 开头。向前搜索则没有这个漏洞：它会一直退到下一个非标点字符。
//
// 于是：
//   单行字数 <= chars_per_line  —— 算术保证，恒成立
//   行数                        —— 取决于标点位置，不是纯算术。真实的行数由
//                                  tests/test_qpq_wrap.c 对**整个题库**逐条断言。
#pragma once

#include <stddef.h>

// 一行最多支持多少字。界面层实际用的最大值是 13（16px 那档），留到 32 是余量。
// 超过这个值的请求会明确失败（返回 0），而不是在栈上越界 —— 宁可失败得响亮。
#define QPQ_WRAP_MAX_LINE 32

// 折行缓冲容量。界面层用一块模块级静态缓冲承载所有层级的折行结果，所以必须按
// **最费的那个调用方**开，而不是按平均：
//
//   最长文案是解析 60 字（QPQ_EXPLAIN_MAX_CHARS），24px 每行 8 字
//   60 字 x 3 字节（CJK 与全角标点）= 180 字节
//   断点前移最多让行数比 60/8 多出若干，按最坏 10 个换行算 = 10 字节
//   结尾 NUL = 1 字节
//   合计 191 字节，取 208 留出余量
//
// 按原文（21 字）去估会得出 70 字节，第一次折一条两行解析就会溢出。
#define QPQ_WRAP_CAPACITY 208

// 把 text 折成每行 chars_per_line 个字符，换行用 '\n'。
// 成功返回写入的字节数（不含结尾 NUL）；失败（容量不足 / 参数非法）返回 0，
// 并把 out 置为空串 —— 不留半截字符串。
size_t qpq_wrap_utf8(const char *text, int chars_per_line, char *out, size_t capacity);

// UTF-8 字符串的字符数（码点数）。版式预算与断言都靠它。
// 非法首字节按 1 字节计，只求不越界读。
unsigned int qpq_utf8_length(const char *text);

// 只数前 max_bytes 个字节之内的字符数（遇到 NUL 也停）。
// 用于「句子被填空位切开的左半段有多少个字符」这种场景 —— 左半段不是一个完整
// 的 NUL 结尾字符串，而是原句的一个前缀。
unsigned int qpq_utf8_length_prefix(const char *text, size_t max_bytes);
